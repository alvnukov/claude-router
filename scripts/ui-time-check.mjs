import assert from 'node:assert/strict';
import { resetIn } from '../internal/ui/web/src/api.ts';

const now = '2026-09-27T00:00:00Z';
for (const [reset, expected] of [
  ['2026-10-03T14:26:00Z', 'Сброс через 6 дн. 14 ч.'],
  ['2026-09-28T00:00:00Z', 'Сброс через 1 дн.'],
  ['2026-09-27T02:05:00Z', 'Сброс через 2 ч. 5 мин'],
  ['2026-09-27T01:00:00Z', 'Сброс через 1 ч.'],
  ['2026-09-27T00:59:00Z', 'Сброс через 59 мин'],
  ['2026-09-27T00:00:01Z', 'Сброс через 1 мин'],
  [now, 'Ожидается обновление лимита'],
  ['2026-09-26T23:59:00Z', 'Ожидается обновление лимита'],
  ['0001-01-01T00:00:00Z', 'Время сброса неизвестно'],
  ['invalid', 'Время сброса неизвестно'],
]) assert.equal(resetIn(reset, now), expected);

console.log('PASS limit reset durations');
